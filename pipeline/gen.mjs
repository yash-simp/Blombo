// Turns out/zone_<key>_server.json sidecars into game/server/world.gen.ts and game/src/world/colliders.gen.ts.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs"
const KEYS = ["lantern", "willow", "coral", "frost", "ember", "moon"]
// node gen.mjs [key ...]: only the listed zones (default: every zone that has been built)
const only = process.argv.slice(2)
const zones = KEYS.map((k) => ((!only.length || only.includes(k)) && existsSync(`out/zone_${k}_server.json`) ? JSON.parse(readFileSync(`out/zone_${k}_server.json`, "utf8")) : null))
let world = "// Generated by the Blender pipeline (pipeline/gen.mjs): zone anchors (local metres) and water masks.\n"
world += "export interface ZoneData {\n  anchors: Record<string, number[] | number[][]>\n  mask: { n: number; cell: number; ext: number; bits: string }\n}\n"
world += "export const ZONE_DATA: (ZoneData | null)[] = [\n"
for (const z of zones) world += z ? `  ${JSON.stringify({ anchors: z.anchors, mask: z.mask })},\n` : "  null,\n"
world += "]\n"
writeFileSync("../game/server/world.gen.ts", world)
mkdirSync("../game/src/world", { recursive: true })
let col = "// Generated by the Blender pipeline (pipeline/gen.mjs): invisible colliders per zone, local metres.\n"
col += "// [centreX, baseY, centreZ, width, height, depth, yaw]\n"
col += "export const ZONE_COLLIDERS: number[][][] = [\n"
for (const z of zones) col += z ? `  ${JSON.stringify(z.colliders)},\n` : "  [],\n"
col += "]\n"
writeFileSync("../game/src/world/colliders.gen.ts", col)
console.log("world.gen.ts", world.length, "colliders.gen.ts", col.length)
